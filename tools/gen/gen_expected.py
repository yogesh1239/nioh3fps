"""Generate src/expected.h from Nioh3.exe.unpacked.exe (the decrypted exe).

Usage: python tools/gen/gen_expected.py <Nioh3.exe.unpacked.exe> <out.h>
Every hook site gets: a wildcarded AOB that must match exactly once in .text at
the expected RVA, and the exact decrypted bytes over the same span. The hosts of
the P1/P2 stubs get their RUNTIME_FUNCTION and full original UNWIND_INFO bytes.
"""
import sys, os, struct
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 're'))
import relib

exe, out = sys.argv[1], sys.argv[2]
N = relib.Img(exe)

# name, aob_rva, min_len, hook_off (offset of the hooked address from aob_rva), required
SITES = [
    ('GETFPS',      0x46594,  16, 0, 1),
    ('CLOCK',       0x5ad5f8, 16, 0, 1),
    ('P1',          0x5ad6a2, 16, 0, 1),
    ('H2',          0x39e4e4, 16, 0, 1),
    ('P2',          0x39e520, 23, 6, 1),   # span 0x39e520..0x39e537, hook at 0x39e526
    ('GETTIMESTEP', 0x46484,  16, 0, 0),
    ('CAM',         0x567070, 16, 0, 0),
    ('CAM2',        0x20dda0c,16, 0, 0),
    ('LEGACY',      0x5a6bb0, 16, 0, 0),
    ('XELLSITE',    0x4a538c, 16, 0, 0),
]

def unique_aob(a, mn):
    for n in (mn, 20, 24, 28, 32, 40, 48, 64):
        p = N.aob(a, n); h = N.aob_search(p, limit=3)
        if len(h) == 1 and h[0] == a:
            return p
    raise SystemExit(f'no unique AOB at {a:#x}')

pe_off = struct.unpack_from('<I', N.mem, 0x3c)[0]
timestamp = struct.unpack_from('<I', N.mem, pe_off + 8)[0]
size_of_image = struct.unpack_from('<I', N.mem, pe_off + 24 + 56)[0]

L = ['/* Generated by tools/gen/gen_expected.py from Nioh3.exe.unpacked.exe. Do not edit. */',
     '#pragma once', '#include <stdint.h>', '',
     f'#define EXP_PE_TIMESTAMP 0x{timestamp:08X}u',
     f'#define EXP_SIZE_OF_IMAGE 0x{size_of_image:08X}u',
     f'#define EXP_G_RVA 0x{0x46594 + 7 + N.i32(0x46594 + 3):X}u',
     f'#define EXP_C60_RVA 0x{0x39e526 + 8 + N.i32(0x39e526 + 4):X}u',
     '']
names = []
for name, a, mn, hoff, req in SITES:
    p = unique_aob(a, mn)
    toks = p.split()
    if len(toks) < hoff + 5:
        raise SystemExit(f'{name}: span too short')
    exact = N.mem[a:a + len(toks)]
    L.append(f'static const char EXP_{name}_AOB[] = "{p}";')
    L.append(f'static const uint8_t EXP_{name}_BYTES[{len(exact)}] = {{' + ','.join(f'0x{b:02X}' for b in exact) + '};')
    L.append(f'#define EXP_{name}_RVA 0x{a:X}u')
    L.append(f'#define EXP_{name}_HOOKOFF {hoff}')
    L.append(f'#define EXP_{name}_REQUIRED {req}')
    L.append('')
    names.append(name)

assert abs(N.f32(0x39e526 + 8 + N.i32(0x39e526 + 4)) - 60.0) == 0.0

import pefile
pe = pefile.PE(exe, fast_load=True)
d = pe.OPTIONAL_HEADER.DATA_DIRECTORY[3]
for tag, host in (('P1HOST', 0x5ad5f8), ('P2HOST', 0x39e4e4)):
    rf = None
    for i in range(0, d.Size, 12):
        b, e, u = struct.unpack_from('<III', N.mem, d.VirtualAddress + i)
        if b == host:
            rf = (b, e, u); break
    assert rf, tag
    b, e, u = rf
    ver, flags = N.mem[u] & 7, N.mem[u] >> 3
    cnt = N.mem[u + 2]
    assert ver == 1 and not (flags & 4) and (N.mem[u + 3] & 15) == 0, tag
    n = 4 + 2 * ((cnt + 1) & ~1)
    ub = N.mem[u:u + n]
    L.append(f'#define EXP_{tag}_BEGIN 0x{b:X}u')
    L.append(f'#define EXP_{tag}_END 0x{e:X}u')
    L.append(f'#define EXP_{tag}_UNWIND_RVA 0x{u:X}u')
    L.append(f'static const uint8_t EXP_{tag}_UNWIND[{n}] = {{' + ','.join(f'0x{x:02X}' for x in ub) + '};')
    L.append('')
open(out, 'w', newline='\n').write('\n'.join(L) + '\n')
print('wrote', out, names)
