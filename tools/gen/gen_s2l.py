"""Derive relocatable S2L anchors from the read-only unpacked image.
Run with python -I tools/gen/gen_s2l.py <exe> <header>.
RVAs here are derivation/test hints, never installer expectations.
"""
import sys
import pefile
import capstone as cs

pe = pefile.PE(sys.argv[1], fast_load=True)
img = pe.get_memory_mapped_image()
text = next(s for s in pe.sections if s.Name.rstrip(b'\0') == b'.text')
ts = text.VirtualAddress
data = img[ts:ts + text.Misc_VirtualSize]
md = cs.Cs(cs.CS_ARCH_X86, cs.CS_MODE_64)
md.detail = True
# name, start, end, hook offset. Field displacements are wildcarded and decoded.
anchors = [
    ('GETFPS', 0x46594, 0x465bc, 0),
    ('CLOCK', 0x5ad5f8, 0x5ad622, 0),
    ('P1', 0x5ad670, 0x5ad6d8, 0x32),
    ('H2', 0x39e4e4, 0x39e4fb, 0),
    ('P2', 0x39e520, 0x39e537, 6),
    ('GETTIMESTEP', 0x46484, 0x464c4, 0),
    ('CAM', 0x567070, 0x567087, 0),
    ('CAM2', 0x20dda0c, 0x20dda37, 0),
    ('LEGACY', 0x5a6bb0, 0x5a6bc2, 0),
    ('XELL', 0x4a538c, 0x4a53a0, 0),
    ('TAKE', 0x3d20eb, 0x3d2102, 0),
    ('HELP', 0x19df57e, 0x19df599, 5),
    ('SCENE', 0x123aa20, 0x123aa3f, 0),
    ('PUBLISH', 0x412748, 0x41277a, 0),
    ('FRAME', 0x5acf80, 0x5acfa4, 0),
    ('S_FIELDS', 0x39e679, 0x39e699, 0),
    ('SLEEP', 0x1a7494b, 0x1a7495f, 9),
    ('ONLINE', 0x85834, 0x8585e, 0),
    ('ONLINE2', 0x85948, 0x8595c, 0),
    ('ONLINE1', 0x85930, 0x85944, 0),
]
# S speed fields are obtained from the stack builder instead; derive S.fps from P2.
anchors[15] = ('S_FIELDS', 0x5ac725, 0x5ac751, 0)
lines = ['/* Generated by tools/gen/gen_s2l.py; no runtime RVA expectations. */',
         '#pragma once', 'static const anchor_def anchors[] = {']
for name, start, end, hook in anchors:
    ins = list(md.disasm(img[start:end], start))
    if not ins or ins[-1].address + ins[-1].size != end:
        raise SystemExit(f'{name}: incomplete instruction range')
    mask = list(img[start:end])
    for i in ins:
        off = i.address - start
        # RIP and all game field displacements; stack/prologue layout remains checked.
        if i.disp_size and any(o.type == cs.x86.X86_OP_MEM and
                              o.mem.base not in (cs.x86.X86_REG_RSP, cs.x86.X86_REG_RBP, cs.x86.X86_REG_RAX)
                              for o in i.operands):
            mask[off+i.disp_offset:off+i.disp_offset+i.disp_size] = [None] * i.disp_size
        if i.group(cs.CS_GRP_CALL) or i.group(cs.CS_GRP_JUMP):
            if i.imm_size:
                mask[off+i.imm_offset:off+i.imm_offset+i.imm_size] = [None] * i.imm_size
    pat = ' '.join('??' if x is None else f'{x:02X}' for x in mask)
    # Online predicate shapes from docs/re/ONLINE_FLAG.md. Keep branch bytes
    # checked, including +34 (wildcarding it makes ONLINE1 nonunique).
    # The installer still decodes and cross-checks the global/field operands.
    online_patterns = {
        'ONLINE': '48 83 EC 28 48 8B 05 ?? ?? ?? ?? 33 C9 48 85 C0 74 06 83 78 34 01 74 09 E8 ?? ?? ?? ?? 84 C0 74 02 B1 01 8A C1 48 83 C4 28 C3',
        'ONLINE2': '48 8B 05 ?? ?? ?? ?? 48 85 C0 74 08 83 78 34 02 0F 94 C0 C3',
        'ONLINE1': '48 8B 05 ?? ?? ?? ?? 48 85 C0 74 08 83 78 34 01 0F 94 C0 C3',
    }
    if name in online_patterns:
        pat = online_patterns[name]
        mask = [None if x == '??' else int(x, 16) for x in pat.split()]
    fixed = next(i for i, x in enumerate(mask) if x is not None)
    hits = []
    p = 0
    while True:
        p = data.find(bytes([mask[fixed]]), p)
        if p < 0: break
        s = p - fixed
        if s >= 0 and s + len(mask) <= len(data) and all(x is None or data[s+j] == x for j, x in enumerate(mask)):
            hits.append(ts+s)
        p += 1
    if hits != [start]: raise SystemExit(f'{name}: nonunique {hits}')
    lines.append(f'    {{"{name}", "{pat}", {hook}, 0x{start:X}}},')
    print(f'{name}: unique at {start:#x}, hook {start+hook:#x}')
lines.append('};')
open(sys.argv[2], 'w', newline='\n').write('\n'.join(lines) + '\n')
