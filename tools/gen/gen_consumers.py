"""Read-only S2C-P signatures; RVAs here are generator seeds, never runtime targets."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 're'))
import relib

im = relib.Img(sys.argv[1], cache=False)
def sig(at):
    for length in range(20, 112, 8):
        s = im.aob(at, length)
        if im.aob_search(s) == [at]:
            return s
    raise ValueError(f'No unique signature: {at:x}')

# name, seed, hook offset (negative = resolve only), kind
sites = [('P-G',0x46594,0,'CG_FPS'),
         ('P-G helper',0x42f0fc,-1,'CG_HELPER'),
         ('P-X inputs',0x42dccd,7,'CG_XINPUT'),
         ('P-X steps',0x42dcff,12,'CG_XSTEPS'),
         ('P-X chr offset',0x404824,-1,'CG_CHROFF'),
         ('P-Ph',0x2de300,0,'CG_PH'),
         ('P-Ph count offset',0x197cf21,-1,'CG_PHOFF'),
         ('P-Ph substep caller',0x197cf37,-1,'CG_PHRET'),
         ('P-Ph substeps',0x2fed9dc,0,'CG_PHSTEP'),
         ('P-Gov global',0x5af50a,-1,'CG_GOV'),
         ('P-Gov setting',0x12a407b,0,'CG_SETTING')]
# Actual clock stores and clock snapshot copying; object identity is checked at runtime.
for at in [0x39e42a,0x5ad689,0x5adc6b,0x5af5d2,0x5af5ec,0x2705250,
           0x5adc9f,0x27051f0,0x27051fc]:
    sites.append((f'P-Gov store {at:x}',at,0,'CG_STORE'))
sites.append(('P-X accumulator',0x42dd98,-1,'CG_XACC'))
known = [0x42f105,0x42d264,0x12b619,0x20ff99,0xb119a,0x231da0,0x901bb3,
         0x433a85,0x90817c,0x2b2f59,0x127200,0x5c0420,0x396713,0x5fb365,
         0x4362fd,0xefafc,0x5fb817,0x4afe3d,0x8f236b,0x27ec52,0x68894a,
         0x231cb1,0x8b28b8,0x3cdb69,0x435935,0x55dc51,0x27d5fc,0x27d057,
         0x27463b,0x27487d,0x26fed7,0x270da1,0xfaabe,0x7d4bd2,0x7d4c02,
         0x927bce,0x5af52b,0x5af687,0x5af6a4,0x5af6c4,
         0x2978676]  # Input hold: native GetFps; float dt is fixed separately.
assert all(im.mem[r-5] == 0xe8 and r + im.i32(r-4) == 0x46594 for r in known)
out = ['/* Generated by tools/gen/gen_consumers.py; all patterns unique in .text. */',
       'static const cp_anchor cp_anchors[] = {']
for name,at,off,kind in sites:
    pattern = sig(at)
    if kind == 'CG_HELPER':
        tokens = pattern.split(); tokens[3] = '??'; pattern = ' '.join(tokens)
        assert im.aob_search(pattern) == [at]
    out.append(f'    {{"{name}", "{pattern}", {off}, {kind}}},')
out += ['};','static const char *const cp_known_aobs[] = {']
for r in known:
    out.append(f'    "{sig(r-5)}", /* ret {r:#x} */')
out += ['};','']
Path(sys.argv[2]).write_text('\n'.join(out))
print(f'Generated {len(sites)} anchors, {len(known)} known GetFps callers')
