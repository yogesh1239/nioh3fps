import sys
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parents[1]/'re'))
import relib
im=relib.Img(sys.argv[1],cache=False)
def sig(at,minimum=20):
 for length in range(minimum,112,8):
  s=im.aob(at,length)
  if im.aob_search(s)==[at]: return s
 raise ValueError(hex(at))
# Probe catalog indices: all direct B/B? rows, known A/C, explicit denylist.
rate={1,3,4,5,7,8,11,12,16,26,27,28,29,30,31}
rounded={2,6,9,10,13,14,17,18,32,33,34}
core=set(range(1,16))
known=[0x42f105,0x42d264,0x12b619,0x20ff99,0xb119a,0x231da0,0x901bb3,
 0x433a85,0x90817c,0x2b2f59,0x127200,0x5c0420,0x396713,0x5fb365,
 0x4362fd,0xefafc,0x5fb817,0x4afe3d,0x8f236b,0x27ec52,0x68894a,
 0x231cb1,0x8b28b8,0x3cdb69,0x435935,0x55dc51,0x27d5fc,0x27d057,
 0x27463b,0x27487d,0x26fed7,0x270da1,0xfaabe,0x7d4bd2,0x7d4c02]
lines=['/* Generated by tools/gen/gen_consumer_fixes.py. */','static const cf_direct cf_directs[] = {']
for i in sorted(rate|rounded|{15}):
 policy='CF_FLOAT' if i==15 else 'CF_RATE' if i in rate else 'CF_ROUND'
 lines.append(f'    {{{i}, {policy}, {int(i in core)}, "GetFps {known[i]:x}"}},')
lines+=['};','static const cf_outer cf_outers[] = {']
# All 20 classified helper outers; only the two hot shrine B rows are core.
outers=[(0x42ea6b,'CF_RATE',1),(0x434e5a,'CF_RATE',1),
 (0x43b822,'CF_KNOWN',0),(0x43babd,'CF_KNOWN',0),
 (0x43bf01,'CF_RATE',0),(0x43bf1a,'CF_RATE',0),(0x7accd9,'CF_RATE',0),
 (0x5ea556,'CF_RATE',0),(0x689caa,'CF_RATE',0)]
outers += [(ret,'CF_KNOWN',0) for ret in (0x398e1f,0x3992de,0x5bc62d,
 0x5e969e,0x9fd67d,0x9fd824,0x2042093,0x23ad9a3,0x23ad9bd,0x23adaa5,0x23adabf)]
specified={
 0x5ea556:'E8 ?? ?? ?? ?? F3 0F 59 05 ?? ?? ?? ?? E8 ?? ?? ?? ?? 0F 28 D8 E8 ?? ?? ?? ?? 84 C0 74 09',
 0x689caa:'E8 ?? ?? ?? ?? 49 8B 88 A0 03 00 00 F3 0F 59 87 C4 0D 00 00 48 85 C9 74 1E F3 0F 10 9E A4 00 00 00',
 0x5bc62d:'E8 ?? ?? ?? ?? F3 41 0F 59 C1 4C 8D 45 D7',
 0x2042093:'E8 ?? ?? ?? ?? F3 0F 59 D0 48 8B CB',
}
for ret,policy,core in outers:
 pattern=specified[ret] if ret in specified else sig(ret-5)
 if im.aob_search(pattern)!=[ret-5] or im.mem[ret-5]!=0xe8 or ret+im.i32(ret-4)!=0x42f0fc:
  raise ValueError(f'nonunique/wrong helper target at {ret:x}')
 lines.append(f'    {{"outer {ret:x}", "{pattern}", {policy}, {core}}},')
lines+=['};','static const cf_patch cf_patches[] = {']
for name,at,off,kind in [('X leaf',0x42dde4,0,0),('inline e7050d',0xe7050d,0,1),('inline 117c051',0x117c02d,0x24,2),('input hold 29786a6',0x297869a,0xc,3),('float efafc',0xefb3e,0,4)]:
 lines.append(f'    {{"{name}", "{sig(at,max(20,off+12))}", {off}, {kind}}},')
lines+=['};','']
Path(sys.argv[2]).write_text('\n'.join(lines))
